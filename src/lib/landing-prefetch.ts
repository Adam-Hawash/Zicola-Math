// المشكلة: شاشة التحميل الأولى كانت بتستنى الكونفيج والجاليري والإحصائيات
// بس — وأقسام الرئيسية (الدروس/التحديات) كانت تبدأ تحميل بياناتها **بعد**
// فتح المنصة، فكل قسم بيظهر بعد ثواني بسبيبنر لوحده.
// الحل: شاشة التحميل نفسها بتجيب بيانات الأقسام دي كمان (بنفس التوازي
// — مفيش وقت زيادة) وتحفظها هنا. وكل قسم بيفتح يلاقي البيانات جاهزة.
// - take = استهلاك مرة واحدة: القسم ياخد الكاش وأول تحديث بعده يجيب طازة.
// ============================================================

var cache: Record<string, Promise<any>> = {}

/** إشعال تحميل مسبق من شاشة التحميل (أو أي حتة تانية) */
export function prefetchLanding(url: string): Promise<any> {
  if (!cache[url]) {
    cache[url] = fetch(url)
      .then(function (r) { return r.json() })
      .catch(function () { return null })
  }
  return cache[url]
}

/** القسم ياخد البيانات الجاهزة (ويمسحها) — بيرجع null لو مفيش */
export function takeLanding(url: string): Promise<any> | null {
  var p = cache[url] || null
  if (p) delete cache[url]
  return p
}
